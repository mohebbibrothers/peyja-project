def main() -> None:
    conn = sqlite3.connect(DB_PATH)
    rows = conn.execute(
        "SELECT id, ig_id, json_extract(raw,'$.caption.text') FROM raw_items "
        "WHERE kind='media' ORDER BY id"
    ).fetchall()
    conn.close()

    samples: list[dict] = []
    for i, s in enumerate(SYNTHETIC, start=1):
        samples.append(
            {
                "id": f"gold-{i:03d}",
                "source_username": "synthetic",
                "ig_media_id": "REPLACE_ME",
                "synthetic": True,
                **s,
            }
        )

    missing = []
    for idx, (raw_id, ig_id, caption) in enumerate(rows, start=5):
        if raw_id not in LABELS:
            missing.append(raw_id)
            continue
        price, old, cat, brand, colors, sizes, vol, spf, stock, note = LABELS[raw_id]
        samples.append(
            {
                "id": f"gold-{idx:03d}",
                "source_username": "farmashop_aras",
                "ig_media_id": str(ig_id),
                "caption": caption or "",
                "price_toman": price,
                "old_price_toman": old,
                "category": cat,
                "brand": brand,
                "colors": colors,
                "sizes": sizes,
                "volume_ml": vol,
                "spf": spf,
                "stock_state": stock,
                "notes": note,
            }
        )

    if missing:
        raise SystemExit(f"برچسب ندارند: {missing}")
    if len(LABELS) != len(rows):
        raise SystemExit(f"تعداد برچسب‌ها ({len(LABELS)}) ≠ رسانه‌ها ({len(rows)})")

    OUT_PATH.write_text(
        json.dumps(samples, ensure_ascii=False, indent=2), encoding="utf-8"
    )
    priced = sum(1 for s in samples if s["price_toman"] is not None)
    print(f"✅ {len(samples)} نمونه → {OUT_PATH}")
    print(f"   دارای قیمت: {priced} | بدون قیمت: {len(samples) - priced}")


if __name__ == "__main__":
    main()
